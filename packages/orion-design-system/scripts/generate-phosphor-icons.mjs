const assets = process.argv[2];
if (!assets) {
  console.error("usage: node scripts/generate-phosphor-icons.mjs <phosphor package/assets dir>");
  process.exit(2);
}

function pathData(weight, file) {
  const name = weight === "fill" ? `${file}-fill` : file;
  const svg = readFileSync(join(assets, weight, `${name}.svg`), "utf8");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0 || !svg.includes('viewBox="0 0 256 256"')) {
    throw new Error(`${weight}/${name}.svg is not a single 256×256 path icon`);
  }
  return paths.join(" ");
}

const lines = (weight) =>
  Object.entries(ICONS)
    .map(([swiftName, file]) => `        .${swiftName}: "${pathData(weight, file)}",`)
    .join("\n");

const out = `// Generated by scripts/generate-phosphor-icons.mjs — do not edit by hand.
// Phosphor Icons, MIT License, Copyright (c) 2023 Phosphor Icons.
// SVG path data on a 256×256 grid.

enum PhosphorPaths {
    static let regular: [OrionIcon: String] = [
${lines("regular")}
    ]

    static let fill: [OrionIcon: String] = [
${lines("fill")}
    ]
}
`;

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "../Sources/OrionDesignSystem/Icons/PhosphorPaths.swift"), out);
console.log(`Wrote ${Object.keys(ICONS).length} icons.`);
