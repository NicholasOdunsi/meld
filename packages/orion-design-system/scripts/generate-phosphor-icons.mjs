#!/usr/bin/env node
// Regenerates Sources/OrionDesignSystem/Icons/PhosphorPaths.swift from the
// Phosphor icon set (MIT, https://phosphoricons.com).
//
//   npm pack @phosphor-icons/core && tar xzf phosphor-icons-core-*.tgz
//   node scripts/generate-phosphor-icons.mjs <path-to>/package/assets
//
// To add an icon: add a line to ICONS (Swift case name → Phosphor file name),
// run this, then add the case to OrionIcon.swift.
